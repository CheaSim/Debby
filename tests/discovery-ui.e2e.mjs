import assert from 'node:assert/strict'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { createRequire } from 'node:module'
import { _electron as electron } from 'playwright'

const root = resolve(import.meta.dirname, '..'), require = createRequire(import.meta.url)
const userData = await mkdtemp(resolve(tmpdir(), 'debby-discovery-'))
let app, page
const errors = []
try {
  app = await electron.launch({ executablePath: require('electron'), args: ['.'], cwd: root, env: { ...process.env, FINPET_E2E_USER_DATA: userData, FINPET_MARKET_SOURCE: 'demo' } })
  page = await app.firstWindow()
  page.on('pageerror', e => errors.push(e.message))
  await page.waitForSelector('[data-3d-ready=true]', { timeout: 30000 })
  await page.locator('[title="桌宠选项"]').click()
  await page.locator('[title="发现更多陪伴"]').click()
  await page.waitForSelector('.app-discover')
  assert.equal(await page.locator('.discovery-card').count(), 9)
  await page.screenshot({ path: resolve(root, 'work/discovery-home.png') })
  const home = async () => page.getByRole('button', { name: '返回发现', exact: true }).click()
  const open = async title => page.locator('.discovery-card').filter({ has: page.locator('strong', { hasText: title }) }).click()
  await page.getByRole('button', { name: '灵感仪式', exact: true }).click()
  assert.equal(await page.locator('.discovery-card').count(), 2)
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await open('塔罗小屋')
  await page.getByLabel('想问塔罗的问题').fill('怎么让今天放松一点？')
  await page.getByRole('button', { name: '洗牌，开始探索' }).click()
  assert.equal(await page.locator('.tarot-card').count(), 3)
  for (const position of ['此刻', '留意', '下一小步']) await page.getByRole('button', { name: `翻开${position}的牌`, exact: true }).click()
  assert.equal(new Set(await page.locator('.tarot-card.revealed strong').allTextContents()).size, 3)
  assert.match(await page.locator('.ritual-note').textContent(), /娱乐.*投资/)
  await page.screenshot({ path: resolve(root, 'work/discovery-tarot.png') })
  await page.getByRole('button', { name: '和 Debby 聊聊这张牌' }).click()
  await page.waitForSelector('.app-dialogue')
  assert.match(await page.getByRole('textbox', { name: '对 Debby 说' }).inputValue(), /娱乐塔罗.*怎么让今天放松一点/)
  assert.equal((await page.evaluate(() => window.finpet.getChatState())).messages.length, 0, 'Passing a card to chat must not automatically send it')
  assert.equal((await page.evaluate(() => window.finpet.getVoiceState())).active, false)
  await page.getByRole('tab', { name: '发现', exact: true }).click()
  await page.getByRole('button', { name: '重新洗牌' }).click()
  await page.getByRole('button', { name: '一张牌' }).click()
  await page.getByRole('button', { name: '洗牌，开始探索' }).click()
  assert.equal(await page.locator('.tarot-card').count(), 1)
  await page.getByRole('button', { name: '翻开此刻的提醒的牌', exact: true }).click()
  await home()
  await open('今日签')
  await page.getByRole('button', { name: '翻开今日签', exact: true }).click()
  const sign = await page.locator('.oracle-paper').textContent()
  await home(); await open('今日签')
  assert.equal(await page.locator('.oracle-paper').textContent(), sign)
  await page.screenshot({ path: resolve(root, 'work/discovery-oracle.png') })
  await home(); await open('盘前准备')
  await page.getByRole('checkbox').first().check()
  assert.match(await page.locator('.local-save-status').textContent(), /已保存/)
  await home(); await open('收盘手记')
  await page.getByLabel('复盘心情').selectOption('有收获')
  await page.getByLabel('今天学到的一件事').fill('先写计划，再做判断。')
  await page.getByLabel('下次的一点改变').fill('给自己保留休息时间。')
  await page.getByRole('button', { name: '保存这页手记' }).click()
  await page.reload(); await page.waitForSelector('[data-3d-ready=true]', { timeout: 30000 })
  await page.getByRole('tab', { name: '发现', exact: true }).click()
  await open('收盘手记')
  assert.equal(await page.getByLabel('今天学到的一件事').inputValue(), '先写计划，再做判断。')
  assert.equal(await page.getByLabel('复盘心情').inputValue(), '有收获')
  await home(); await open('盘前准备')
  assert.equal(await page.getByRole('checkbox').first().isChecked(), true)
  await home(); await open('动作小剧场')
  const gestures = ['greet', 'celebrate', 'comfort', 'notify', 'nod', 'shake', 'heart', 'shy', 'think', 'stretch', 'bow', 'clap']
  const poses = new Set()
  for (let i = 0; i < gestures.length; i++) {
    await page.locator('.action-grid button').nth(i).click()
    await page.waitForFunction(name => document.querySelector('.three-pet-host').dataset.behavior === name, gestures[i])
    const initial = await page.locator('.three-pet-host').getAttribute('data-gesture-pose')
    await page.waitForFunction(pose => document.querySelector('.three-pet-host').dataset.gesturePose !== pose, initial)
    await page.waitForTimeout(180)
    poses.add(await page.locator('.three-pet-host').getAttribute('data-gesture-pose'))
  }
  assert.ok(poses.size >= 10, 'Curated actions must produce distinct actual rig poses')
  await page.screenshot({ path: resolve(root, 'work/discovery-actions.png') })
  await home(); await open('一分钟放松')
  await page.getByRole('button', { name: '开始一分钟' }).click()
  await page.getByRole('button', { name: '结束放松' }).waitFor()
  await page.getByRole('tab', { name: '行情', exact: true }).click()
  await page.getByRole('tab', { name: '发现', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '开始一分钟' }).isVisible(), true, 'Hidden experiences must stop their timer')
  await home()
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setResizable(true); w.setSize(540, 700) })
  await page.waitForFunction(() => innerWidth === 540)
  await open('塔罗小屋')
  const layout = await page.locator('#discover-view').evaluate(el => ({ width: el.clientWidth, scroll: el.scrollWidth }))
  assert.ok(layout.scroll <= layout.width, JSON.stringify(layout))
  await page.screenshot({ path: resolve(root, 'work/discovery-narrow.png') })
  assert.deepEqual(errors, [])
  console.log('Discovery E2E passed: 9 features, card draws, chat drafts, daily sign, persistence, 12 rig animations, relaxation lifecycle, narrow UI')
} catch (error) {
  await page?.screenshot({ path: resolve(root, 'work/discovery-failure.png') }).catch(() => {})
  throw error
} finally {
  await app?.close()
  await rm(userData, { recursive: true, force: true })
}
